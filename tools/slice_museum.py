#!/usr/bin/env python3
"""Cut the museum theme's art sheets (art/museum/) into single images and write js/art-museum.js.

Usage: python3 tools/slice_museum.py

Unlike the hotel sheets, these came back in mixed grids with duplicates, so each sheet lists exactly
which cell becomes which picture (cells are numbered from 1, left to right, top to bottom).
"""
import json
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from slice_sheets import bounds, object_box, profile  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'art' / 'museum'
OUT = 'img-museum'


def seq(start, n):
    return {i + 1: start + i for i in range(n)}


# Staff: [(sheet, cell)] for staff 1..48, chosen to match each job (see docs/museum-theme.md).
A, B, C, O = 'staff-a', 'staff-b', 'staff-c', 'staff-objects'
STAFF_CELLS = {
    1: (C, 11), 2: (B, 2), 3: (B, 3), 4: (B, 4), 5: (A, 1), 6: (B, 14), 7: (A, 6), 8: (A, 15),
    9: (O, 5), 10: (A, 4), 11: (C, 8), 12: (A, 13), 13: (A, 9), 14: (O, 10), 15: (O, 12), 16: (A, 12),
    17: (C, 1), 18: (C, 2), 19: (C, 3), 20: (C, 4), 21: (C, 5), 22: (A, 10), 23: (C, 7), 24: (O, 1),
    25: (O, 2), 26: (B, 7), 27: (B, 1), 28: (B, 5), 29: (A, 5), 30: (A, 2), 31: (C, 15), 32: (O, 14),
    33: (B, 11), 34: (C, 6), 35: (A, 16), 36: (O, 15), 37: (B, 15), 38: (A, 3), 39: (A, 14), 40: (A, 8),
    41: (O, 11), 42: (A, 7), 43: (O, 9), 44: (O, 7), 45: (A, 11), 46: (O, 16), 47: (O, 13), 48: (C, 16),
}

SHEETS = {
    'egypt': dict(cols=4, rows=4, size=384, detect=True, pick={c: ('guests', str(n)) for c, n in seq(49, 14).items()}),
    'medieval': dict(cols=4, rows=4, size=384, detect=True, pick={c: ('guests', str(n)) for c, n in seq(63, 14).items()}),
    'classical': dict(cols=4, rows=4, size=384, detect=True, pick={c: ('guests', str(n)) for c, n in seq(77, 14).items()}),
    'natural-history': dict(cols=4, rows=4, size=384, detect=True, pick={c: ('guests', str(n)) for c, n in seq(91, 14).items()}),
    'materials': dict(cols=2, rows=2, size=192, detect=False, inset=0.05,
                      pick={1: ('items', 's'), 2: ('items', 'c'), 3: ('items', 'w'), 4: ('items', 'k')}),
    'curators': dict(cols=2, rows=2, size=256, detect=False, inset=0.05,
                     pick={3: ('players', '0'), 1: ('players', '1'), 2: ('players', '2'), 4: ('players', '3')}),
    'galleries': dict(cols=3, rows=2, size=320, detect=False, inset=0.03, zoom=0.86,
                      pick={1: ('rooms', 'R-free'), 2: ('rooms', 'Y-free'), 3: ('rooms', 'B-free'),
                            4: ('rooms', 'R-occ'), 5: ('rooms', 'Y-occ'), 6: ('rooms', 'B-occ')}),
}
for sheet in (A, B, C, O):
    SHEETS[sheet] = dict(cols=4, rows=4, size=320, detect=True,
                         pick={cell: ('staff', str(sid)) for sid, (sh, cell) in STAFF_CELLS.items() if sh == sheet})


def cut(name, spec, art):
    img = Image.open(SRC / f'{name}.webp').convert('RGB')
    xs = bounds(profile(img, 0), spec['cols'], spec['detect'])
    ys = bounds(profile(img, 1), spec['rows'], spec['detect'])
    inset = spec.get('inset', 0.02)
    for cell, (group, key) in spec['pick'].items():
        r, c = divmod(cell - 1, spec['cols'])
        x0, x1 = xs[c]
        y0, y1 = ys[r]
        dx, dy = round((x1 - x0) * inset), round((y1 - y0) * inset)
        x0, x1, y0, y1 = x0 + dx, x1 - dx, y0 + dy, y1 - dy
        if spec.get('tight'):
            x0, y0, x1, y1 = object_box(img, (x0, y0, x1, y1))
        side = min(x1 - x0, y1 - y0)
        cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
        if spec.get('zoom'):
            side = round(side * spec['zoom'])
            cy = y1 - side // 2
        box = (cx - side // 2, cy - side // 2, cx - side // 2 + side, cy - side // 2 + side)
        out = img.crop(box).resize((spec['size'], spec['size']), Image.LANCZOS)
        rel = f'{OUT}/{group}/{key}.webp'
        dest = ROOT / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        out.save(dest, 'WEBP', quality=82, method=6)
        art.setdefault(group, {})[key] = rel


def main():
    art = {}
    for name, spec in SHEETS.items():
        cut(name, spec, art)
        print(f'{name}: {len(spec["pick"])} images')
    js = ('// Generated by tools/slice_museum.py from art/museum/. Do not edit by hand.\n'
          f'const ART_MUSEUM = {json.dumps(art, indent=2, sort_keys=True)};\n')
    (ROOT / 'js' / 'art-museum.js').write_text(js)
    assert len(art['guests']) == 56 and len(art['staff']) == 48, (len(art['guests']), len(art['staff']))


if __name__ == '__main__':
    main()
